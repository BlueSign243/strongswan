def der(tag, body):
    n = len(body)
    size = bytes([n]) if n < 128 else bytes([0x80 + (n.bit_length()+7)//8]) + n.to_bytes((n.bit_length()+7)//8, 'big')
    return bytes([tag]) + size + body

def oid(s):
    arcs = list(map(int,s.split('.')))
    out = b''
    for n in [40*arcs[0]+arcs[1],*arcs[2:]]:
        octets = [n & 127]
        while n >> 7:
            n >>= 7
            octets.insert(0,128 | (n & 127))
        out += bytes(octets)
    return der(6,out)

# RFC8032 Edwards25519 reference formulas; independent from OpenSSL provider.
p = 2**255-19
d = -121665 * pow(121666,p-2,p) % p
By = 4 * pow(5,p-2,p) % p
xx = (By*By-1)*pow(d*By*By+1,p-2,p)%p
Bx = pow(xx,(p+3)//8,p)
if (Bx*Bx-xx)%p: Bx = Bx*pow(2,(p-1)//4,p)%p
if Bx & 1: Bx = p-Bx
B = (Bx,By)
L = 2**252+27742317777372353535851937790883648493

def add(a,b):
    x,y=a;u,v=b;z=d*x*u*y*v%p
    return ((x*v+u*y)*pow(1+z,p-2,p)%p,(y*v+x*u)*pow(1-z,p-2,p)%p)

def mul(a,n):
    out=(0,1)
    while n:
        if n&1:out=add(out,a)
        a=add(a,a);n>>=1
    return out

def enc(a):
    x,y=a
    return (y | ((x&1)<<255)).to_bytes(32,'little')

def ed(seed,msg):
    h=hashlib.sha512(seed).digest();a=int.from_bytes(h[:32],'little')
    a=(a & ((1<<254)-8)) | (1<<254)
    A=enc(mul(B,a));r=int.from_bytes(hashlib.sha512(h[32:]+msg).digest(),'little')%L
    R=enc(mul(B,r));k=int.from_bytes(hashlib.sha512(R+A+msg).digest(),'little')%L
    return A,R+((r+k*a)%L).to_bytes(32,'little')
